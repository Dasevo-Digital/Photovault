/// Der Ländername zur Anzeige, ausgehend von dem, was in der Aufnahme
/// steht.
///
/// Gibt für `null` und Leeres einen leeren Text zurück, damit die
/// Aufrufer keine Sonderfälle brauchen. Alles Unbekannte kommt
/// unverändert wieder – auch Regionen und Städte, die versehentlich hier
/// hereingereicht werden.
String landAnzeige(String? englisch, String sprache) {
  if (englisch == null || englisch.isEmpty) return '';
  if (!sprache.startsWith('de')) return englisch;
  return _laendernamenDeNachEnglisch[englisch] ?? englisch;
}

/// selbstgemachte Liste danebengreift.
///
/// **Nachgeschlagen wird über den ISO-Code, nicht über den englischen
/// Namen.** Benennt GeoNames morgen ein Land um, ändert das hier nichts.
///
/// Von den Einträgen sind 97 mit dem englischen Namen identisch (Andorra,
/// Malta, Panama …). Sie stehen trotzdem hier – eine Liste, die nur die
/// Unterschiede führt, macht aus jedem fehlenden Eintrag die stille Frage,
/// ob er vergessen wurde oder gleich ist.
///
/// **Zwei Einträge fehlen mit Absicht.** GeoNames führt noch die
/// aufgelösten Codes `AN` (Niederländische Antillen) und `CS` (Serbien und
/// Montenegro); CLDR beantwortet beide mit ihrem Nachfolger und machte
/// daraus „Curaçao" und „Serbien" – zwei Länder, die dann zweimal in der
/// Liste stünden, eines davon unter falschem Namen. Für sie bleibt es beim
/// englischen Namen aus dem Katalog, und der ist der richtige.
